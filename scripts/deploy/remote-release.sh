#!/usr/bin/env bash
# Раскладка выпуска на сервере: исполняется на сервере через `ssh … bash -s`.
#
# Повторяет ручную процедуру из DEPLOYMENT.md: архив распаковывается в новый
# каталог выпуска, и только потом на него переставляется симлинк `current`.
# Пока симлинк не переставлен, сайт отдаёт прежний выпуск — упавшая на любом
# шаге выкладка ничего не ломает.
#
# Аргументы:
#   1 — каталог проекта на сервере (<WEBROOT>)
#   2 — путь к загруженному архиву сборки
#   3 — имя выпуска (отметка времени и хэш коммита)
#   4 — сколько выпусков хранить (по умолчанию 5)
#   5 — ожидаемая SHA-256 архива; выкладка её всегда передаёт
#
# Права: если каталог проекта доступен пользователю на запись, sudo не нужен
# вовсе — это предпочтительная схема (отдельный пользователь выкладки без
# привилегий). Если каталог принадлежит root, как при ручной выкладке, команды
# идут через `sudo -n`: `-n` запрещает спрашивать пароль, иначе выкладка
# зависла бы до тайм-аута.
set -euo pipefail

WEBROOT="${1:?не задан каталог проекта}"
ARCHIVE="${2:?не задан путь к архиву}"
RELEASE="${3:?не задано имя выпуска}"
KEEP="${4:-5}"
EXPECTED_SHA="${5:-}"

case "$WEBROOT" in
  /*) ;;
  *) echo "каталог проекта должен быть абсолютным путём: $WEBROOT" >&2; exit 1 ;;
esac
case "$RELEASE" in
  *[!A-Za-z0-9._-]*|'') echo "недопустимое имя выпуска: $RELEASE" >&2; exit 1 ;;
esac

REL_DIR="$WEBROOT/releases/$RELEASE"

if [ -d "$WEBROOT" ] && [ -w "$WEBROOT" ]; then
  SUDO=""
else
  SUDO="sudo -n"
fi

CREATED=0
SWITCHED=0

# Архив удаляется всегда; недоделанный каталог выпуска — только если симлинк
# на него так и не переставили, иначе упавшие выкладки копились бы на диске.
cleanup() {
  rm -f "$ARCHIVE" 2>/dev/null || true
  # Архив лежит в одноразовом каталоге из mktemp -d; если это не так
  # (ручной запуск с архивом в /tmp), rmdir непустого каталога просто откажет.
  rmdir "$(dirname "$ARCHIVE")" 2>/dev/null || true
  if [ "$CREATED" = 1 ] && [ "$SWITCHED" = 0 ]; then
    $SUDO rm -rf "$REL_DIR"
  fi
}
trap cleanup EXIT

# Архив распаковывается с повышенными правами, поэтому до распаковки
# убеждаемся, что это тот самый файл, который собрал раннер: обычный файл,
# принадлежащий нам, с совпадающей контрольной суммой.
if [ -L "$ARCHIVE" ] || [ ! -f "$ARCHIVE" ] || [ ! -O "$ARCHIVE" ]; then
  echo "архив не является обычным файлом текущего пользователя: $ARCHIVE" >&2
  exit 1
fi
if [ -n "$EXPECTED_SHA" ]; then
  ACTUAL_SHA="$(sha256sum "$ARCHIVE" | cut -d' ' -f1)"
  if [ "$ACTUAL_SHA" != "$EXPECTED_SHA" ]; then
    echo "контрольная сумма архива не совпадает — выкладка отменена" >&2
    exit 1
  fi
fi

if [ -e "$REL_DIR" ]; then
  echo "выпуск уже существует: $REL_DIR" >&2
  exit 1
fi

$SUDO mkdir -p "$REL_DIR"
CREATED=1
$SUDO tar -xzf "$ARCHIVE" -C "$REL_DIR" --no-same-owner --no-same-permissions

# Архив без index.html — признак битой сборки. Переставлять на него симлинк
# нельзя: сайт стал бы пустым.
if [ ! -s "$REL_DIR/index.html" ]; then
  echo "в выпуске нет index.html — симлинк не переставлен" >&2
  exit 1
fi

# Под sudo файлы из архива получили бы владельца с раннера сборки.
if [ -n "$SUDO" ]; then
  $SUDO chown -R root:root "$REL_DIR"
fi
$SUDO chmod -R u=rwX,go=rX "$REL_DIR"

# Относительная цель: симлинк остаётся верным, если каталог проекта перенесут.
$SUDO ln -sfn "releases/$RELEASE" "$WEBROOT/current"
SWITCHED=1
echo "выложено: $REL_DIR"

# Уборка: оставляем KEEP свежих выпусков. Текущий исключается явно — после
# ручного отката он может оказаться и не среди свежих.
CURRENT="$(basename "$(readlink "$WEBROOT/current")")"
cd "$WEBROOT/releases"
# `|| true`: когда удалять нечего, grep возвращает 1, и при pipefail это
# обрушило бы уже состоявшуюся выкладку.
ls -1 | sort -r | tail -n "+$((KEEP + 1))" | { grep -vx "$CURRENT" || true; } | while IFS= read -r old; do
  $SUDO rm -rf -- "$WEBROOT/releases/$old"
  echo "удалён старый выпуск: $old"
done
